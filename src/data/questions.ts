import type { Question, QuestionKind } from '../types'
import { TOPIC_BY_ID } from './curriculum'

const KIND_POINTS: Record<QuestionKind, number> = {
  theory: 100,
  formula: 150,
  problem: 200,
  custom: 100,
}

let seq = 0

/** Демонстрационный банк. Полный банк заменим материалами из учебников и КТП. */
const q = (
  topicId: string,
  kind: QuestionKind,
  text: string,
  options: string[],
  correct: number,
  explanation: string,
): Question => {
  const topic = TOPIC_BY_ID[topicId]
  seq += 1
  return {
    id: `bq-${seq}`,
    topicId,
    grade: topic?.grade,
    kind,
    text,
    options,
    correct,
    answer: options[correct],
    explanation,
    points: KIND_POINTS[kind],
    source: 'base',
  }
}

